#!/bin/bash
# deploy-agent.sh — Deploy k8s-agent to remote server(s)
# Usage: ./deploy-agent.sh user@remote-ip [user2@remote-ip2 ...]
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$SCRIPT_DIR/.env"

if [ $# -lt 1 ]; then
    echo "Usage: $0 user@remote-ip [user2@remote-ip2 ...]"
    echo "Example: $0 datdt@10.10.10.60 datdt@10.10.10.133"
    exit 1
fi

TOKEN_EXPLICIT=false
if [ -n "$AGENT_AUTH_TOKEN" ]; then
    TOKEN_EXPLICIT=true
fi

# Auto-load AGENT_AUTH_TOKEN and CONTROL_PLANE_URL from .env if present and unset in shell
if [ -f "$ENV_FILE" ]; then
    if [ "$TOKEN_EXPLICIT" = "false" ]; then
        VAL=$(grep -E '^[[:space:]]*AGENT_AUTH_TOKEN=' "$ENV_FILE" | tail -n 1 | cut -d '=' -f2- | tr -d '\r' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/^["'"'"']//' -e 's/["'"'"']$//')
        if [ -n "$VAL" ]; then
            AGENT_AUTH_TOKEN="$VAL"
            TOKEN_EXPLICIT=true
            echo "🔑 Loaded AGENT_AUTH_TOKEN from $ENV_FILE"
        fi
    fi
    if [ -z "$CONTROL_PLANE_URL" ]; then
        VAL=$(grep -E '^[[:space:]]*CONTROL_PLANE_URL=' "$ENV_FILE" | tail -n 1 | cut -d '=' -f2- | tr -d '\r' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/^["'"'"']//' -e 's/["'"'"']$//')
        if [ -n "$VAL" ]; then
            CONTROL_PLANE_URL="$VAL"
            echo "🌐 Loaded CONTROL_PLANE_URL from $ENV_FILE ($CONTROL_PLANE_URL)"
        fi
    fi
fi

# Auto-generate AGENT_AUTH_TOKEN if still empty
if [ -z "$AGENT_AUTH_TOKEN" ]; then
    echo "🔑 Generating fallback AGENT_AUTH_TOKEN (TOKEN_EXPLICIT=false)..."
    if command -v openssl >/dev/null 2>&1; then
        AGENT_AUTH_TOKEN=$(openssl rand -hex 32)
    else
        AGENT_AUTH_TOKEN=$(od -vN 32 -An -tx1 /dev/urandom 2>/dev/null | tr -d ' \n' || date +%s%N | sha256sum | head -c 64)
    fi

    if [ -f "$ENV_FILE" ]; then
        printf "\n# Auto-generated by deploy-agent.sh\nAGENT_AUTH_TOKEN=%s\n" "$AGENT_AUTH_TOKEN" >> "$ENV_FILE"
        echo "💾 Appended AGENT_AUTH_TOKEN to $ENV_FILE"
    fi
fi

if [ -n "$CONTROL_PLANE_URL" ]; then
    echo "🎯 Central Control Plane URL: $CONTROL_PLANE_URL"
fi

# Build agent for Linux amd64 once before deploying to hosts
echo "🔨 Building agent for linux/amd64..."
GOOS=linux GOARCH=amd64 go build -o k8s-agent ./cmd/agent

# Temporary local file setup for credentials
TMP_SUFFIX="$$"
LOCAL_ENV_FILE=".agent.env.${TMP_SUFFIX}"
LOCAL_BIN_COPY="k8s-agent-new.${TMP_SUFFIX}"

cp k8s-agent "$LOCAL_BIN_COPY"
cat > "$LOCAL_ENV_FILE" << EOF
AGENT_AUTH_TOKEN=${AGENT_AUTH_TOKEN}
EOF
if [ -n "$CONTROL_PLANE_URL" ]; then
    cat >> "$LOCAL_ENV_FILE" << EOF
CONTROL_PLANE_URL=${CONTROL_PLANE_URL}
EOF
fi
chmod 600 "$LOCAL_ENV_FILE" 2>/dev/null || true

# Ensure local temporary files are cleaned up upon exit or interrupt
trap 'rm -f "$LOCAL_ENV_FILE" "$LOCAL_BIN_COPY"' EXIT INT TERM

# Loop over each target host
for REMOTE in "$@"; do
    echo ""
    echo "============================================================"
    echo "🚀 Deploying k8s-agent to $REMOTE..."
    echo "============================================================"

    # Copy binary and environment file to remote in a single scp command
    echo "📦 Copying files to $REMOTE (/tmp/)..."
    scp "$LOCAL_BIN_COPY" "$LOCAL_ENV_FILE" "$REMOTE:/tmp/"

    # Install and configure systemd user service via interactive ssh (-t)
    echo "⚙️ Configuring and starting k8s-agent systemd service on $REMOTE..."
    ssh -t "$REMOTE" "
      mkdir -p ~/.config/systemd/user && \
      mkdir -p ~/.k8s-agent/logengine && \
      (systemctl --user stop k8s-agent 2>/dev/null || true) && \
      mv -f /tmp/$LOCAL_BIN_COPY ~/k8s-agent && \
      chmod +x ~/k8s-agent && \
      if [ \"$TOKEN_EXPLICIT\" = \"false\" ] && [ -f ~/.k8s-agent/agent.env ]; then
        REMOTE_EXISTING_TOKEN=\$(grep -E '^[[:space:]]*AGENT_AUTH_TOKEN=' ~/.k8s-agent/agent.env | tail -n 1 | cut -d '=' -f2- | tr -d '\r' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/^[\"\'']//' -e 's/[\"\'']$//')
        if [ -n \"\$REMOTE_EXISTING_TOKEN\" ]; then
          sed -i \"s|^AGENT_AUTH_TOKEN=.*|AGENT_AUTH_TOKEN=\$REMOTE_EXISTING_TOKEN|\" /tmp/$LOCAL_ENV_FILE
          echo '🔑 Preserved existing remote AGENT_AUTH_TOKEN from ~/.k8s-agent/agent.env'
        fi
      fi && \
      mv -f /tmp/$LOCAL_ENV_FILE ~/.k8s-agent/agent.env && \
      chmod 600 ~/.k8s-agent/agent.env && \
      cat > ~/.config/systemd/user/k8s-agent.service << 'UNIT'
[Unit]
Description=K8sControl Monitoring Agent
After=network.target

[Service]
Type=simple
EnvironmentFile=-%h/.k8s-agent/agent.env
ExecStart=%h/k8s-agent --port 9100 --engine-dir %h/.k8s-agent/logengine
Restart=always
RestartSec=5
MemoryHigh=40M
MemoryMax=50M

[Install]
WantedBy=default.target
UNIT
      systemctl --user daemon-reload && \
      systemctl --user enable k8s-agent && \
      systemctl --user restart k8s-agent && \
      (loginctl enable-linger \$(whoami) 2>/dev/null || true) && \
      echo '' && \
      echo '✅ Agent successfully updated & running on port 9100' && \
      echo '📊 Test: curl http://localhost:9100/health'
    "

    REMOTE_HOST=$(echo "$REMOTE" | cut -d@ -f2)
    echo ""
    echo "🎉 Successfully deployed to $REMOTE!"
    echo "   Infrastructure Fleet Registry (/hosts)"
    echo "   Endpoint: http://${REMOTE_HOST}:9100"
done

echo ""
echo "✨ All deployments completed successfully."

